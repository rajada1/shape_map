import 'dart:convert';

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';

/// A country in the generated geographic catalog.
@immutable
class GeoCatalogCountry {
  /// Creates a catalog country.
  const GeoCatalogCountry({
    required this.iso2,
    required this.iso3,
    required this.nameEn,
    required this.namePt,
    required this.nameEs,
    required this.region,
    required this.hasFocus,
  });

  /// ISO 3166-1 alpha-2 code, also the region id in [ShapeMaps.world].
  final String iso2;

  /// ISO 3166-1 alpha-3 code.
  final String iso3;

  /// English name.
  final String nameEn;

  /// Portuguese name.
  final String namePt;

  /// Spanish name.
  final String nameEs;

  /// World region (`south_america`, `europe`, ...).
  final String region;

  /// Whether an admin-1 layer exists for this country.
  final bool hasFocus;

  /// The name in [languageCode] (`en`, `pt` or `es`), falling back to English.
  String name(String languageCode) => switch (languageCode.toLowerCase()) {
    'pt' => namePt,
    'es' => nameEs,
    _ => nameEn,
  };
}

/// An admin-1 subdivision in the generated geographic catalog.
@immutable
class GeoCatalogSubdivision {
  /// Creates a catalog subdivision.
  const GeoCatalogSubdivision({
    required this.code,
    required this.countryIso,
    required this.nameEn,
    required this.namePt,
    required this.nameEs,
    required this.type,
  });

  /// Canonical code such as `BR-SP`, also the region id in the country layer.
  final String code;

  /// ISO alpha-2 of the owning country.
  final String countryIso;

  /// English name.
  final String nameEn;

  /// Portuguese name.
  final String namePt;

  /// Spanish name.
  final String nameEs;

  /// Source type (`State`, `Province`, ...).
  final String type;

  /// The name in [languageCode] (`en`, `pt` or `es`), falling back to English.
  String name(String languageCode) => switch (languageCode.toLowerCase()) {
    'pt' => namePt,
    'es' => nameEs,
    _ => nameEn,
  };
}

/// Localized country and subdivision names matching the generated maps.
///
/// The catalog is a compact package asset generated by the same pipeline as
/// the maps, so every code here matches a region id. Load it once with
/// [GeoCatalog.load]; the decoded instance is cached.
class GeoCatalog {
  GeoCatalog._(this.countries, this._subdivisions)
    : _countriesByIso = {
        for (final country in countries) country.iso2: country,
      };

  static GeoCatalog? _cached;
  static Future<GeoCatalog>? _loading;

  /// Asset path inside this package.
  static const assetPath = 'packages/shape_map/assets/catalog/geo_names.json';

  /// Every country in the world map, in catalog order.
  final List<GeoCatalogCountry> countries;

  final Map<String, GeoCatalogCountry> _countriesByIso;
  final Map<String, List<GeoCatalogSubdivision>> _subdivisions;

  /// Loads and caches the catalog, decoding the JSON off the UI isolate.
  static Future<GeoCatalog> load() {
    final cached = _cached;
    if (cached != null) return Future.value(cached);
    return _loading ??= _load();
  }

  /// The cached catalog, or null before [load] completes.
  static GeoCatalog? get instance => _cached;

  static Future<GeoCatalog> _load() async {
    try {
      final json = await rootBundle.loadString(assetPath);
      final catalog = await compute(parse, json);
      return _cached = catalog;
    } finally {
      _loading = null;
    }
  }

  /// Parses the compact catalog JSON. Exposed for tests and isolates.
  static GeoCatalog parse(String json) {
    final decoded = jsonDecode(json);
    if (decoded is! Map<String, dynamic>) {
      throw const FormatException('Invalid geo catalog.');
    }
    final countries = <GeoCatalogCountry>[
      for (final row in (decoded['countries'] as List<dynamic>).cast<List>())
        GeoCatalogCountry(
          iso2: row[0] as String,
          iso3: row[1] as String,
          nameEn: row[2] as String,
          namePt: row[3] as String,
          nameEs: row[4] as String,
          region: row[5] as String,
          hasFocus: row[6] == 1,
        ),
    ];
    final subdivisions = <String, List<GeoCatalogSubdivision>>{
      for (final entry
          in (decoded['subdivisions'] as Map<String, dynamic>).entries)
        entry.key: List.unmodifiable(<GeoCatalogSubdivision>[
          for (final row in (entry.value as List<dynamic>).cast<List>())
            GeoCatalogSubdivision(
              code: row[0] as String,
              countryIso: entry.key,
              nameEn: row[1] as String,
              namePt: row[2] as String,
              nameEs: row[3] as String,
              type: row[4] as String,
            ),
        ]),
    };
    return GeoCatalog._(List.unmodifiable(countries), subdivisions);
  }

  /// The country with [iso2], or null.
  GeoCatalogCountry? country(String iso2) =>
      _countriesByIso[iso2.trim().toUpperCase()];

  /// Admin-1 subdivisions of [countryIso], empty when the country has none.
  List<GeoCatalogSubdivision> subdivisions(String countryIso) =>
      _subdivisions[countryIso.trim().toUpperCase()] ?? const [];

  /// Total number of subdivisions across every country.
  int get subdivisionCount =>
      _subdivisions.values.fold(0, (sum, list) => sum + list.length);
}
